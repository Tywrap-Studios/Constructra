package org.tywrapstudios.constructra.api;

/*
    Hello fellow developer!
    Welcome to the API package of Constructra.

    Sadly some parts of the API need resources from outside the package, you will need the bare content
    mod too in order to make it properly function.
    Sometimes it may also be heavily related to the workflows of Tywrap Studios, some things might be odd to you
    or may not be applicable to your situation.

    Index:
    block/v1 -> Different helper classes and methods for block-related stuff.
    item/v1 -> Different helper classes and methods for item-related stuff.
    math/v1 -> Classes that expand on what we can do in regard to mathematics.
        Think about making calculations from plain Strings, and Unit Systems.
    resource/v1 -> Everything that handles the Resources part of this mod.
        Think about Nodes, harvesting, saving them to the world, etc.

    You might be interested in the BlossomBridge API too, which handles Logging and Config.
    See: https://github.com/Tywrap-Studios/Constructra/blob/1.20.1-dev/README.md
 */