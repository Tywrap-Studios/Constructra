package org.tywrapstudios.constructra.api;

/*
    Hello fellow developer!
    Welcome to the API package of Constructra.

    Sadly some parts of the API need resources from outside the package, you will need the bare content
    mod too in order to make it properly function.

   |Index:
   \block           Different helper classes and methods for block-related stuff.
   \client          API related to client side developing.
    \gui            Graphical User Interface API
     \widget        Widgets for GUIs.
   \inventory       Helper classes for Inventories.
   \item            Different helper classes and methods for item-related stuff.
   \math            Classes that expand on what we can do in regard to mathematics.
    |                   e.g. making calculations from plain Strings, and Unit Systems.
    \exception      Exceptions related to math.
    \ruleset        Contains stuff mostly related to "rules" when it comes to mathematics and algebra.
   \resource        Everything that handles the Resources part of this mod.
    |                   e.g. Nodes, harvesting, saving them to the world, etc.
   \screen          Classes that help with the creation and utilisation of Screens.

    You might be interested in the BlossomBridge API too, which handles Logging and Config.
    See: https://github.com/Tywrap-Studios/BlossomBridge/blob/master/README.md
 */